// TestFIOLowerSurnameConfidence закрепляет уверенность и причину решения.
// Находка со строчной буквы принята по соседству, а не по самому слову,
// поэтому её уверенность обязана быть ниже, чем у находки с заглавной буквы.
func TestFIOLowerSurnameConfidence(t *testing.T) {
	cases := []struct {
		name   string
		text   string
		value  string
		conf   float64
		reason string
	}{
		{"опора слева", "меня зовут тимур нагимов", "тимур нагимов", fioLowerSurnameConf, "fio:lower_surname_after_name"},
		{"опора справа", "клиент нагимов тимур ринатович", "нагимов тимур ринатович", fioLowerSurnameConf, "fio:lower_surname_before_name"},
		{"опора на якорь", "меня зовут нагимов", "нагимов", fioLowerSurnameConf, "fio:lower_surname_anchor"},
	}

	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			kept, _ := Resolve(NewFIODetector().Detect(NewDoc(c.text)), ConfMedium)
			if len(kept) != 1 {
				t.Fatalf("текст %q: найдено %d фрагментов, ожидался один: %v", c.text, len(kept), kept)
			}
			if got := c.text[kept[0].Start:kept[0].End]; got != c.value {
				t.Fatalf("текст %q: фрагмент %q, ожидался %q", c.text, got, c.value)
			}
			if kept[0].Conf != c.conf {
				t.Fatalf("текст %q: уверенность %v, ожидалась %v", c.text, kept[0].Conf, c.conf)
			}
			if kept[0].Reason != c.reason {
				t.Fatalf("текст %q: причина %q, ожидалась %q", c.text, kept[0].Reason, c.reason)
			}
		})
	}
	if fioLowerSurnameConf >= ConfAnchored {
		t.Fatalf("уверенность фамилии со строчной буквы %v не ниже уверенности находки по якорю %v",
			fioLowerSurnameConf, ConfAnchored)
	}
}

