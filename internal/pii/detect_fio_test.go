// TestFIOLowerInitials закрепляет связку «фамилия и инициалы» со строчной
// буквы. В переписке пишут именно так, и без этого разбора имя со строчной
// буквы держалось на 0.628 против 0.941 в обычном тексте.
func TestFIOLowerInitials(t *testing.T) {
	det := NewFIODetector()
	cases := []struct {
		name string
		text string
		want []string
	}{
		{"фамилия и два инициала", "клиент: лебедев л. л.", []string{"лебедев л. л"}},
		{"инициалы перед фамилией", "и е.э. морозова подписала", []string{"е.э. морозова"}},
		{"заглавными по-прежнему работает", "Клиент: Лебедев Л. Л.", []string{"Лебедев Л. Л"}},
		// Буква адресного сокращения инициалом не бывает: «г. Ростов» это
		// город, и маска на нём закрывала адрес отделения банка.
		{"город не имя", "Банкомат по адресу г. Ростов, ул. Садовая", nil},
		{"дом не имя", "отделение находится в д. иванов, рядом с парком", nil},
		// Фамилия без словарного подтверждения со строчной буквы не годится:
		// одного окончания мало.
		{"незнакомая фамилия со строчной не берётся", "в акте о. штруделев указан", nil},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			got := det.Detect(NewDoc(c.text))
			var vals []string
			for _, s := range got {
				vals = append(vals, c.text[s.Start:s.End])
			}
			if len(vals) != len(c.want) {
				t.Fatalf("получено %q, ожидалось %q", vals, c.want)
			}
			for i := range vals {
				if vals[i] != c.want[i] {
					t.Fatalf("фрагмент %d: %q, ожидалось %q", i, vals[i], c.want[i])
				}
			}
		})
	}
}
