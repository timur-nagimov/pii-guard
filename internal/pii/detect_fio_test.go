// fioResolved прогоняет детектор имён и снимает пересечения тем же способом,
// что и конвейер сервиса. Фамилия со строчной буквы находится фрагментом,
// который накрывает уже найденное имя, поэтому проверять её на голом списке
// детектора бессмысленно: значение имеет то, что останется после Resolve.
func fioResolved(text string, minConf float64) []string {
	kept, _ := Resolve(NewFIODetector().Detect(NewDoc(text)), minConf)
	out := make([]string, 0, len(kept))
	for _, s := range kept {
		out = append(out, text[s.Start:s.End])
	}
	return out
}

