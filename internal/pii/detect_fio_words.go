// fioMergeWordSets собирает один набор слов из нескольких.
func fioMergeWordSets(sets ...map[string]bool) map[string]bool {
	out := make(map[string]bool)
	for _, set := range sets {
		for w := range set {
			out[w] = true
		}
	}
	return out
}

