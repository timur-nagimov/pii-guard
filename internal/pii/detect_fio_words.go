// fioWordSet собирает набор слов для быстрой проверки по одному слову.
func fioWordSet(words ...string) map[string]bool {
	return fioWordSetOf(words)
}

// fioWordSetOf собирает набор из общих перечней и отдельных слов. Перечни
// только читаются, слова копируются в новый набор: собирать набор через
// append прямо в общий перечень нельзя — append пишет в чужой массив и портит
// остальные наборы, собранные из того же перечня.
func fioWordSetOf(groups ...[]string) map[string]bool {
	n := 0
	for _, g := range groups {
		n += len(g)
	}
	out := make(map[string]bool, n)
	for _, g := range groups {
		for _, w := range g {
			out[dict.Normalize(w)] = true
		}
	}
	return out
}

