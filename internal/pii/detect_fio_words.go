// fioExpandSuffixes собирает окончания из основ и падежных хвостов.
func fioExpandSuffixes(stems, tails []string) []string {
	out := make([]string, 0, len(stems)*len(tails))
	for _, s := range stems {
		for _, t := range tails {
			out = append(out, s+t)
		}
	}
	return out
}

