// noInflect — названия, для которых склонения не порождаются: их косвенные
// формы совпадают с обычными словами или с именами людей.
var noInflect = map[string]bool{
	"владимир": true,
	"орел":     true,
	"шахты":    true,
	"киров":    true,
}

// placeIndex — таблица «нормализованное название -> вид». Строится один раз
// при инициализации пакета и дальше не изменяется.
var placeIndex = buildPlaceIndex()

// buildPlaceIndex собирает таблицу названий вместе с порождёнными склонениями.
func buildPlaceIndex() map[string]string {
	idx := make(map[string]string, len(cityNames)*4+len(countryNames))
	for _, c := range countryNames {
		idx[NormalizePlace(c)] = KindCountry
	}
	for _, c := range cityNames {
		name := NormalizePlace(c)
		addPlace(idx, name)
		if noInflect[name] {
			continue
		}
		for _, form := range inflectPlace(name) {
			addPlace(idx, form)
		}
	}
	return idx
}

// addPlace добавляет название, не затирая уже известное: страна важнее города.
func addPlace(idx map[string]string, name string) {
	if name == "" {
		return
	}
	if _, busy := idx[name]; busy {
		return
	}
	idx[name] = KindCity
}

// NormalizePlace приводит название к виду, в котором оно хранится в словаре:
// нижний регистр, буква «ё» заменена на «е», пробелы схлопнуты.
func NormalizePlace(s string) string {
	s = strings.ToLower(strings.TrimSpace(s))
	s = strings.ReplaceAll(s, "ё", "е")
	return strings.Join(strings.Fields(s), " ")
}

// geoVowels — гласные, по последней букве определяется способ склонения.
const geoVowels = "аеиоуыэюя"

// inflectPlace порождает частые косвенные формы названия: «Тула» даёт «Туле»,
// «Тулы», «Тулу». Формы нужны потому, что в тексте адрес нередко записан
// предложным падежом: «в Туле, улица Ленина». Составные названия не склоняем:
// их формы слишком разнообразны, а выигрыш мал.
func inflectPlace(name string) []string {
	if strings.Contains(name, " ") || len([]rune(name)) < 4 {
		return nil
	}
	runes := []rune(name)
	base := string(runes[:len(runes)-1])
	switch last := runes[len(runes)-1]; {
	case last == 'а' || last == 'я':
		return []string{base + "е", base + "ы", base + "и", base + "у"}
	case last == 'ь':
		return []string{base + "и", base + "ю"}
	case strings.ContainsRune(geoVowels, last):
		return nil
	default:
		return []string{name + "е", name + "а", name + "у"}
	}
}

// Place возвращает вид географического названия: город или страна.
func Place(name string) (string, bool) {
	kind, ok := placeIndex[NormalizePlace(name)]
	return kind, ok
}

// IsCity сообщает, что название есть в словаре городов.
func IsCity(name string) bool {
	kind, ok := Place(name)
	return ok && kind == KindCity
}

// IsCountry сообщает, что название есть в словаре стран.
func IsCountry(name string) bool {
	kind, ok := Place(name)
	return ok && kind == KindCountry
}
