// TestBirthPlaceFromCorpus закрепляет разбор места рождения на записях, которые
// набор показал как пропущенные. Каждый случай — след настоящего пропуска.
func TestBirthPlaceFromCorpus(t *testing.T) {
	cases := []addrCase{
		// Латинские буквы, похожие на кириллические, приходят из распознанных
		// сканов. Якорь искали по сырому тексту, и «Мeстo pождeния» не
		// совпадало ни с одним якорем.
		{"якорь с латинскими омоглифами", "Мeстo pождeния: гopoд Псков", "гopoд Псков", ConfHigh},
		// Уточнение, чьё это место: без него «заявителя» само принималось за
		// место рождения и маска накрывала его вместо города.
		{"уточнение заявителя", "Место рождения заявителя: город Ярославль", "город Ярославль", ConfHigh},
		{"уточнение ребёнка", "Место рождения ребёнка: г. Нальчик", "г. Нальчик", ConfHigh},
		// Разделители, которых не было в списке допустимых.
		{"значение в квадратных скобках", "МР [город Братск]", "город Братск", ConfHigh},
		{"строка таблицы", "| Место рождения | город Казань |", "город Казань", ConfHigh},
		{"неразрывный пробел", "Место рождения: город Ярославль", "город Ярославль", ConfHigh},
		// Якоря, которых не было в списке.
		{"населённый пункт рождения", "Населённый пункт рождения: с. Дубки", "с. Дубки", ConfHigh},
		{"город рождения", "Страна и город рождения: «Комсомольск-на-Амуре»", "Комсомольск-на-Амуре", ConfHigh},
		// Хвост «область, россия» после запятой в нижнем регистре не входил во
		// фрагмент: слово «московская» не заглавное и не тип, и запятая обрывала
		// место рождения на названии населённого пункта.
		{"хвост области в нижнем регистре", "место рождения: д. михайловка, московская область, россия;",
			"д. михайловка, московская область, россия", ConfHigh},
		{"округ в нижнем регистре", "место рождения: г. калуга, ханты-мансийский автономный округ",
			"г. калуга, ханты-мансийский автономный округ", ConfHigh},
		// Якорь «родина» в разговорной речи: «родина г. воронеж». Раньше слово
		// не было якорем, и место рождения после него не находилось.
		{"якорь родина", "клиент: родина г. воронеж, телефон +7-958-5399176.",
			"г. воронеж", ConfHigh},
	}
	addrRunCases(t, NewBirthPlaceDetector(), TypeBirthPlace, cases)
}

// TestBirthPlaceBeatsAddress закрепляет, что при одинаковых границах побеждает
// место рождения: оно срабатывает только по явному якорю, а адрес — по форме.
// Раньше значение маскировалось, но помечалось чужим типом.
func TestBirthPlaceBeatsAddress(t *testing.T) {
	if Priority(TypeBirthPlace) <= Priority(TypeAddress) {
		t.Fatalf("приоритет места рождения %d не выше адреса %d",
			Priority(TypeBirthPlace), Priority(TypeAddress))
	}
	text := "Место рождения заявителя: д. Заречье, Брянская область, Россия"
	d := NewDoc(text)
	var all []Span
	all = append(all, NewBirthPlaceDetector().Detect(d)...)
	all = append(all, NewAddressDetector().Detect(d)...)
	kept, _ := Resolve(all, 0.5)
	for _, s := range kept {
		if s.Type == TypeAddress && text[s.Start:s.End] == "д. Заречье, Брянская область, Россия" {
			t.Fatalf("значение осталось адресом, а должно быть местом рождения")
		}
	}
}
