import "testing"

// addrCase — случай табличного теста. Пустое поле want означает, что детектор
// не должен найти ничего: проверяем не только полноту, но и отсутствие ложных
// срабатываний на суммах, номерах заказов и упоминаниях городов.
type addrCase struct {
	name string
	text string
	want string
	conf float64
}

// addrSpanTexts возвращает тексты найденных фрагментов для сообщения об ошибке.
func addrSpanTexts(d *Doc, spans []Span) []string {
	out := make([]string, 0, len(spans))
	for _, s := range spans {
		out = append(out, d.Text[s.Start:s.End])
	}
	return out
}

// addrRunCases прогоняет табличный тест для одного детектора. Тест намеренно
// не использует Registry и другие детекторы: проверяется только поведение
// адресного детектора.
func addrRunCases(t *testing.T, det Detector, want Type, cases []addrCase) {
	t.Helper()
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			d := NewDoc(c.text)
			spans := det.Detect(d)
			if c.want == "" {
				if len(spans) != 0 {
					t.Fatalf("ожидалось отсутствие фрагментов, найдено %d: %q", len(spans), addrSpanTexts(d, spans))
				}
				return
			}
			if len(spans) != 1 {
				t.Fatalf("ожидался один фрагмент, найдено %d: %q", len(spans), addrSpanTexts(d, spans))
			}
			s := spans[0]
			if got := d.Text[s.Start:s.End]; got != c.want {
				t.Errorf("фрагмент = %q, ожидался %q", got, c.want)
			}
			if s.Type != want {
				t.Errorf("тип = %s, ожидался %s", s.Type, want)
			}
			if s.Conf != c.conf {
				t.Errorf("уверенность = %.2f, ожидалась %.2f", s.Conf, c.conf)
			}
			if s.Reason == "" {
				t.Error("признаки фрагмента не заполнены")
			}
		})
	}
}

