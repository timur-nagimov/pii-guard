// TestAddressDetectorLineBreak проверяет, что фрагмент не пересекает перевод
// строки. Компонентов два, но они на разных строках, поэтому это два адреса,
// а не один: каждый опознан самостоятельно по сокращённому типу.
func TestAddressDetectorLineBreak(t *testing.T) {
	d := NewDoc("г. Москва\nул. Ленина, 5")
	spans := NewAddressDetector().Detect(d)
	want := []string{"г. Москва", "ул. Ленина, 5"}
	got := addrSpanTexts(d, spans)
	if len(got) != len(want) {
		t.Fatalf("фрагменты = %q, ожидались %q", got, want)
	}
	for i := range want {
		if got[i] != want[i] {
			t.Errorf("фрагмент %d = %q, ожидался %q", i, got[i], want[i])
		}
	}
}

// TestAddressDetectorReason проверяет, что признаки фрагмента перечислены в
// поле Reason: по ним контекстные правила отличают адрес отделения банка от
// адреса человека.
func TestAddressDetectorReason(t *testing.T) {
	cases := []struct {
		text string
		want string
	}{
		{"г. Москва, ул. Тверская, д. 5, кв. 12", "address:city+street+house+flat"},
		{"Тверская 12-45", "address:street+house"},
		{"Зарегистрирован: Россия, 690001", "address:country+postcode"},
		{"Московская обл., г. Химки", "address:region+city"},
	}
	det := NewAddressDetector()
	for _, c := range cases {
		d := NewDoc(c.text)
		spans := det.Detect(d)
		if len(spans) != 1 {
			t.Fatalf("%q: ожидался один фрагмент, найдено %d", c.text, len(spans))
		}
		if spans[0].Reason != c.want {
			t.Errorf("%q: признаки = %q, ожидались %q", c.text, spans[0].Reason, c.want)
		}
	}
}

