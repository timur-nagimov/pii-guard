package pii

import (
	"slices"
	"testing"
)

// docwordsCase — один случай табличного теста: текст и фрагменты, которые
// детектор обязан выделить, в порядке следования в тексте.
type docwordsCase struct {
	name    string
	text    string
	want    []string
	minConf float64
}

// docwordsRun прогоняет детектор по тексту и возвращает выделенные фрагменты
// в виде подстрок, попутно проверяя корректность границ и тип фрагмента.
func docwordsRun(t *testing.T, det Detector, text string, want Type) ([]string, []float64) {
	t.Helper()
	d := NewDoc(text)
	spans := det.Detect(d)
	SortSpans(spans)
	out := make([]string, 0, len(spans))
	confs := make([]float64, 0, len(spans))
	for _, s := range spans {
		if !s.Valid() || s.End > len(text) {
			t.Fatalf("некорректные границы фрагмента: %+v", s)
		}
		if s.Type != want {
			t.Fatalf("ожидался тип %s, получен %s", want, s.Type)
		}
		if s.Reason == "" {
			t.Fatalf("фрагмент без причины срабатывания: %+v", s)
		}
		out = append(out, text[s.Start:s.End])
		confs = append(confs, s.Conf)
	}
	return out, confs
}

// docwordsCheck сверяет фактические фрагменты с ожидаемыми.
func docwordsCheck(t *testing.T, det Detector, typ Type, cases []docwordsCase) {
	t.Helper()
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			got, confs := docwordsRun(t, det, tc.text, typ)
			if !slices.Equal(got, tc.want) {
				t.Fatalf("текст %q: получено %q, ожидалось %q", tc.text, got, tc.want)
			}
			if tc.minConf == 0 {
				return
			}
			for _, c := range confs {
				if c < tc.minConf {
					t.Fatalf("текст %q: уверенность %.2f ниже ожидаемой %.2f", tc.text, c, tc.minConf)
				}
			}
		})
	}
}

