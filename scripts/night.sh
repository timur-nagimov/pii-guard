#!/usr/bin/env bash
# Ночной прогон улучшений: очередь задач, изолированные копии дерева, ворота.
#
# Что делает. Берёт задачи из docs/NIGHT-QUEUE.md, на каждую создаёт отдельную
# копию рабочего дерева и отдельную ветку, запускает агента, прогоняет ворота
# и раскладывает результат по двум корзинам: прошло и не прошло. В main не
# пишет никогда.
#
# Почему именно так. Замер показал, что модель не является узким местом:
# 64 одновременных обращения отработали за 8.5 секунды без единой ошибки,
# 2521 токен в секунду. Узкое место это ноутбук, потому что ворота гоняют
# тесты с детектором гонок и замер качества, а это процессор. Поэтому
# правки идут широко и параллельно, а ворота проходят по одной через замок.
#
# Использование:
#   bash scripts/night.sh --dry-run      показать план и выйти
#   bash scripts/night.sh                прогон
#   bash scripts/night.sh --jobs 8       своё число одновременных задач
#   bash scripts/night.sh --status       что получилось
#
# Перед первым запуском обязательно:
#   bash scripts/gate.sh --init          снять базовую линию качества
#   export ALFAGEN_TOKEN=...             ключ доступа к модели
#   export NODE_EXTRA_CA_CERTS=...       набор удостоверяющих центров

set -o pipefail

cd "$(dirname "$0")/.." || exit 2
ROOT="$PWD"
NIGHT="${NIGHT_DIR:-$ROOT/../night}"
MODEL="${NIGHT_MODEL:-alfagen/deepseek-ai/DeepSeek-V4-Flash-0731}"
