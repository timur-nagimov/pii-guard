DRY=0
STATUS=0

while [ $# -gt 0 ]; do
  case "$1" in
    --dry-run) DRY=1 ;;
    --status)  STATUS=1 ;;
    --jobs)    JOBS="$2"; shift ;;
    --model)   MODEL="$2"; shift ;;
    *) echo "неизвестный ключ: $1"; exit 2 ;;
  esac
  shift
done

