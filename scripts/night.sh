# Замок на воротах. Команды flock на macOS нет, поэтому замок делается
# каталогом: mkdir атомарен, и это тот редкий случай, когда самодельное
# решение и проще, и переносимее готового.
#
# Замок с владельцем, умершим не отпустив его, останавливает весь прогон,
# поэтому проверяется возраст: замок старше часа считается брошенным.
# Час взят с большим запасом, полный прогон ворот занимает единицы минут.
lock_acquire() {
  local waited=0
  while ! mkdir "$GATE_LOCK" 2>/dev/null; do
    if [ -d "$GATE_LOCK" ]; then
      local age
      age=$(( $(date +%s) - $(stat -f %m "$GATE_LOCK" 2>/dev/null || echo 0) ))
      if [ "$age" -gt 3600 ]; then
        echo "замок брошен владельцем, возраст ${age}s, забираю"
        rm -rf "$GATE_LOCK"
        continue
      fi
    fi
    sleep 5
    waited=$((waited + 5))
    if [ "$((waited % 300))" = "0" ]; then echo "жду ворота уже ${waited}s"; fi
  done
}

lock_release() { rm -rf "$GATE_LOCK"; }

run_task() {
  local name="$1"
  local dir="$NIGHT/work/$name"
  local branch="night/$name"
  local log="$NIGHT/logs/$name.log"

  {
    echo "=== $name: начало $(date '+%H:%M:%S') ==="

    # Отдельная копия рабочего дерева. Без неё параллельные задачи правят
    # одни и те же файлы и мешают друг другу до неразличимости.
    git -C "$ROOT" worktree add -b "$branch" "$dir" HEAD 2>&1 || {
      echo "не создать копию дерева"; return 1; }

    # Набор данных. Раньше сюда ставилась ссылка на общий каталог, и это
    # оказалось дефектом, ломающим весь прогон: задача обогащения набора
    # перегенерировала общий dataset.jsonl, после чего ворота ВСЕХ остальных
    # задач мерили по одному набору, а сравнивали с базовой линией, снятой по
    # другому. Каждая из них честно закрывалась с «качество просело».
    #
    # Теперь: большие неизменяемые файлы по ссылке, чтобы не множить 330
    # мегабайт на каждую задачу, а рабочий набор своей копией, потому что
    # именно его перезаписывают.
    mkdir -p "$dir/corpus"
    for f in "$ROOT"/corpus/*; do
      base="$(basename "$f")"
      [ "$base" = "dataset.jsonl" ] && continue
      ln -sf "$f" "$dir/corpus/$base" 2>/dev/null
    done
    if [ "$name" = "dataset" ]; then
      # Задаче обогащения нужен полностью свой набор: она правит и те файлы,
      # что остальным отданы только на чтение.
      rm -f "$dir"/corpus/*
      cp -R "$ROOT/corpus/." "$dir/corpus/" 2>/dev/null
    else
      cp "$ROOT/corpus/dataset.jsonl" "$dir/corpus/dataset.jsonl" 2>/dev/null
    fi

    echo "=== $name: агент пошёл ==="
    task_prompt "$name" | opencode run --auto --dir "$dir" --model "$MODEL" \
      --title "night-$name" 2>&1 | tail -40

    echo "=== $name: ворота $(date '+%H:%M:%S') ==="
    # Ворота гоняют тесты с детектором гонок и замер качества, это процессор
    # целиком. Пускать их параллельно значит получить недостоверные замеры
    # задержки и взаимные помехи, поэтому через замок, по одной.
    # Работу агента надо зафиксировать на ветке, иначе её нет. Агенты не
    # коммитят, и без этого шага утреннее «слить ветку» сливало бы пустоту:
    # правки лежали бы незафиксированными в копии дерева, которую потом
    # убирают. Заодно архив, собираемый в воротах, начинает содержать то,
    # что задача сделала, а не только исходный коммит.
    echo "=== $name: фиксирую работу на ветке ==="
    (
      cd "$dir" || exit 1
      # Набор данных в архив не идёт и в git не заводится: он порождаемый.
      git add -A -- . ':!corpus'
      if git diff --cached --quiet; then
        echo "агент ничего не изменил"
      else
        git -c user.name="night" -c user.email="night@local" \
          commit -q -m "Ночная задача $name" && echo "зафиксировано"
      fi
    )

    # Разведывательные задачи рабочий код не правят, поэтому сравнивать
    # качество с базовой линией не с чем. Им хватает быстрых ворот: формат,
    # анализ, сборка, тесты, ссылки, поставка. Замок им всё равно нужен,
    # потому что тесты с детектором гонок это тот же процессор.
    local gate_args=""
    case " $TASK_READONLY " in
      *" $name "*) gate_args="--quick" ;;
    esac

    lock_acquire
    ( cd "$dir" && bash scripts/gate.sh $gate_args )
    local code=$?
    lock_release

    if [ "$code" = "0" ]; then
      echo "=== $name: ВОРОТА ОТКРЫТЫ ==="
      touch "$NIGHT/passed/$name.ok"
    else
      echo "=== $name: ворота закрыты, код $code ==="
      grep -m1 "ПЛОХО" "$log" > "$NIGHT/parked/$name.fail" 2>/dev/null || \
        echo "ворота закрыты, код $code" > "$NIGHT/parked/$name.fail"
    fi
    echo "=== $name: конец $(date '+%H:%M:%S') ==="
  } > "$log" 2>&1
}

