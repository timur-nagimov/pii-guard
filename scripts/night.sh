# Ограничение числа одновременных задач. Ключа wait -n в bash 3.2, который
# стоит на macOS по умолчанию, нет, поэтому число живых задач считается
# опросом: просто, переносимо и на интервале в секунду ничего не стоит.
PIDS=""
alive_count() {
  local n=0 p
  for p in $PIDS; do
    if kill -0 "$p" 2>/dev/null; then n=$((n + 1)); fi
  done
  echo "$n"
}

for name in "${TASK_NAMES[@]}"; do
  while [ "$(alive_count)" -ge "$JOBS" ]; do sleep 2; done
  run_task "$name" &
  PIDS="$PIDS $!"
  printf '  пошла задача %s\n' "$name"
done

for p in $PIDS; do wait "$p" 2>/dev/null; done

printf '\n\033[1mПрогон закончен.\033[0m\n\n'
bash "$0" --status
